#!/usr/bin/env node
/**
 * EVERY NATIVE CAPACITOR PLUGIN package.json DEPENDS ON MUST BE IN THE SPM
 * MANIFEST THAT `cap sync` JUST WROTE.
 *
 * Build 7 went to TestFlight with @capacitor/browser installed in
 * node_modules, imported by lib/nativeOAuth.ts, and ABSENT from
 * CapApp-SPM/Package.swift — so its native half was never compiled. The app
 * answered `"Browser" plugin is not implemented on ios` and Google sign-in
 * could not start. Nothing failed: the JS half was present, the archive
 * succeeded, Apple accepted the binary.
 *
 * WHAT THIS DOES AND DOES NOT PROVE, said plainly because the greenness must
 * not imply more than it earns:
 *
 *   IT PROVES the generated manifest names every plugin we depend on. That is
 *   an assertion about the INPUT TO THE COMPILER, not about the binary.
 *
 *   IT DOES NOT PROVE the plugin reached the .app. The archive job asserts
 *   that separately, against the built product.
 *
 * WHERE IT RUNS: from ci_post_clone.sh, AFTER `cap sync ios`, in both the
 * compile and archive jobs. It exits non-zero and stops the run. It is
 * deliberately NOT in `npm run verify` — Package.swift is not in the
 * repository, so on a developer machine that has not run sync there is
 * nothing to check, and a check that skips on every machine is a red nobody
 * reads.
 */
import { readFileSync, existsSync } from 'node:fs';

const MANIFEST = 'ios/App/CapApp-SPM/Package.swift';
let failures = 0;
const fail = (m) => { console.log('  FAIL  ' + m); failures++; };
const pass = (m) => console.log('  PASS  ' + m);

if (!existsSync('package.json')) {
  console.log('REFUSED: run this from the repository root; there is no package.json here.');
  process.exit(2);
}

const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
const deps = Object.keys(pkg.dependencies || {});

// @capacitor/core is the JS runtime and @capacitor/cli is tooling; neither is
// a native plugin and neither appears in the manifest. Everything else under
// the @capacitor scope is.
const NOT_PLUGINS = new Set(['@capacitor/core', '@capacitor/cli', '@capacitor/ios', '@capacitor/android']);
const plugins = deps.filter((d) => d.startsWith('@capacitor/') && !NOT_PLUGINS.has(d));

console.log('native Capacitor plugins in package.json: ' + (plugins.length ? plugins.join(', ') : '(none)'));

if (!existsSync(MANIFEST)) {
  console.log('');
  console.log('  FAIL  ' + MANIFEST + ' DOES NOT EXIST.');
  console.log('        It is generated by `npx cap sync ios` and is deliberately not');
  console.log('        committed. If you are seeing this in CI, sync did not run or');
  console.log('        did not finish.');
  process.exit(1);
}

const manifest = readFileSync(MANIFEST, 'utf8');

for (const p of plugins) {
  // The SPM product name is what the manifest references, and it comes from
  // the plugin's own Package.swift rather than from a naming convention we
  // invented. Read it rather than guessing.
  const own = 'node_modules/' + p + '/Package.swift';
  let product = null;
  if (existsSync(own)) {
    const m = readFileSync(own, 'utf8').match(/name:\s*"([^"]+)"/);
    if (m) product = m[1];
  }
  if (!product) { fail(p + ' has no Package.swift of its own — it may not be a native plugin'); continue; }

  if (!manifest.includes('"' + product + '"')) {
    fail(p + ' IS NOT IN THE MANIFEST. Its SPM product "' + product + '" appears nowhere in '
         + MANIFEST + ', so its native half will not be compiled and the app will say'
         + ' "not implemented on ios" at runtime.');
    continue;
  }
  // named as a dependency AND wired into the target — the first without the
  // second still does not compile it in.
  const wired = manifest.includes('.product(name: "' + product + '"');
  if (!wired) fail(p + ' is listed as a package but its product is not a target dependency');
  else pass(p + ' -> ' + product + ', declared and wired into the target');
}

if (plugins.length === 0) {
  console.log('  (nothing to check — no native plugins are installed)');
}

console.log('');
if (failures) {
  console.log(failures + ' FAILED — this is what shipped as build 7.');
  process.exit(1);
}
console.log('OK — the generated manifest names every native plugin we depend on.');
console.log('    NOTE: this is the compiler input. Whether the plugin reached the');
console.log('    binary is asserted separately, on the built product.');
